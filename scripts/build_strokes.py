"""Bundle KanjiVG stroke data for every character in js/kanji-data.js.

Writes js/stroke-data.js. Re-run after editing the word list:
    python scripts/build_strokes.py

Stroke data (c) Ulrich Apel, KanjiVG project, CC BY-SA 3.0.
"""
import json, pathlib, re, urllib.request
from concurrent.futures import ThreadPoolExecutor

TAG = "r20260714"
URL = "https://raw.githubusercontent.com/KanjiVG/kanjivg/{tag}/kanji/{hex}.svg"
root = pathlib.Path(__file__).resolve().parent.parent
words = re.findall(r'\["([^"]+)", "', (root / "js/kanji-data.js").read_text(encoding="utf8"))
chars = sorted({c for w in words for c in w})

def fetch(ch):
    url = URL.format(tag=TAG, hex=f"{ord(ch):05x}")
    svg = urllib.request.urlopen(url, timeout=30).read().decode("utf8")
    paths_block = svg.split('id="kvg:StrokeNumbers')[0]
    strokes = re.findall(r'<path[^>]*\sd="([^"]+)"', paths_block)
    nums = [[float(x), float(y)] for x, y in
            re.findall(r'matrix\(1 0 0 1 ([\d.-]+) ([\d.-]+)\)', svg.split('id="kvg:StrokeNumbers')[1])]
    return ch, {"s": strokes, "n": nums}

with ThreadPoolExecutor(8) as ex:
    data = dict(ex.map(fetch, chars))

out = ("/* Generated by scripts/build_strokes.py from KanjiVG (" + TAG + ").\n"
       " * Stroke data (c) Ulrich Apel, KanjiVG project - CC BY-SA 3.0 - https://kanjivg.tagaini.net */\n"
       "window.KANJI_STROKES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
(root / "js/stroke-data.js").write_text(out, encoding="utf8")
print(f"{len(data)} characters, {len(out) // 1024} KB")
